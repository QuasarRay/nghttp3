#[no_mangle]
pub unsafe extern "C" fn nghttp3_cpymem(
    mut dest: *mut uint8_t,
    mut src: *const uint8_t,
    mut n: size_t,
) -> *mut uint8_t {
    memcpy(dest as *mut ::core::ffi::c_void, src as *const ::core::ffi::c_void, n);
    return dest.offset(n as isize);
}
