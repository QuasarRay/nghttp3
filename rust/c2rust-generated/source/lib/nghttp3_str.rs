pub unsafe extern "C" fn nghttp3_downcase(mut s: *mut uint8_t, mut len: size_t) {
    let mut i: size_t = 0;
    i = 0 as size_t;
    while i < len {
        *s.offset(i as isize) = nghttp3_downcase_byte(*s.offset(i as isize));
        i = i.wrapping_add(1);
    }
}
